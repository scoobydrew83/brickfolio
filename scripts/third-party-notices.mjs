// Writes THIRD_PARTY_NOTICES.md: every runtime package Brickfolio ships (the production dependency tree from
// `npm ls`, without the Cloudflare deploy tool, which only runs at build time) with its version, license and
// license text, plus the Archivo font. Run after installing dependencies:
//   npm run notices
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const BUILD_ONLY = new Set(['@opennextjs/cloudflare']); // deploys to Cloudflare; not part of the app

const tree = JSON.parse(execFileSync('npm', ['ls', '--omit=dev', '--all', '--long', '--json'], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }));

const seen = new Map();
(function walk(deps) {
  for (const [name, d] of Object.entries(deps ?? {})) {
    if (BUILD_ONLY.has(name) || !d.version || !d.path) continue;
    const key = `${name}@${d.version}`;
    if (seen.has(key)) continue;
    let pkg = {};
    try { pkg = JSON.parse(readFileSync(join(d.path, 'package.json'), 'utf8')); } catch { /* listed by npm but not installed (optional) */ }
    if (!existsSync(d.path)) continue;
    const licenseFile = readdirSync(d.path).find((f) => /^(licen[cs]e|copying)(\.|-|$)/i.test(f));
    const license = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type ?? (pkg.licenses ?? []).map((l) => l.type).join(' OR ');
    const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url ?? pkg.homepage ?? '';
    seen.set(key, {
      name, version: d.version, license: license || 'UNKNOWN',
      repo: repo.replace(/^git\+/, '').replace(/^git:\/\//, 'https://').replace(/\.git$/, '').replace(/^github:/, 'https://github.com/'),
      text: licenseFile ? readFileSync(join(d.path, licenseFile), 'utf8').trim() : null,
    });
    walk(d.dependencies);
  }
})(tree.dependencies);

const list = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const font = {
  name: 'Archivo (font)', version: '', license: 'OFL-1.1', repo: 'https://github.com/Omnibus-Type/Archivo',
  text: 'Copyright 2016 The Archivo Project Authors (https://github.com/Omnibus-Type/Archivo).\nLicensed under the SIL Open Font License, Version 1.1 (https://openfontlicense.org). Self-hosted through next/font.',
};
const all = [font, ...list];
const link = (p) => (/^https?:\/\//.test(p.repo) ? `[${p.name}](${p.repo})` : p.name);
const md = [
  '# Third-party notices',
  '',
  'Brickfolio includes the open-source packages below. This file is generated by `npm run notices` from the',
  'production dependency tree; regenerate it instead of editing it by hand.',
  '',
  '| Package | Version | License |',
  '| --- | --- | --- |',
  ...all.map((p) => `| ${link(p)} | ${p.version} | ${p.license} |`),
  '',
  '## License texts',
  '',
  'The full Apache License 2.0 is in [LICENSE](LICENSE). For packages that ship no license file, the license named in the table applies; see the linked repository.',
  '',
  ...all.filter((p) => p.text).flatMap((p) => [`### ${p.name}${p.version ? ` ${p.version}` : ''}`, '', '````text', p.text, '````', '']),
].join('\n');
writeFileSync('THIRD_PARTY_NOTICES.md', `${md}\n`);
const missing = list.filter((p) => !p.text).map((p) => p.name);
console.log(`THIRD_PARTY_NOTICES.md: ${all.length} packages${missing.length ? `; no license file shipped by: ${missing.join(', ')}` : ''}.`);
